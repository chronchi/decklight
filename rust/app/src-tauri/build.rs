use std::path::PathBuf;

fn main() {
    // One data archive per unit (scripts/app/build_app_assets.py), each with its own content id, is embedded in the
    // app library; the app unpacks only the units whose id changed. `web` comes first in assets.json.
    let dir = std::env::var("DECKLIGHT_ASSETS_DIR").map(PathBuf::from).unwrap_or_else(|_| {
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../../data/cache/app/apk")
    });
    let manifest_path = dir.join("assets.json");
    let text = std::fs::read_to_string(&manifest_path).unwrap_or_else(|_| {
        panic!("no {}: run scripts/app/build_app_assets.py first", manifest_path.display())
    });
    let units: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("bad {}: {e}", manifest_path.display()));
    let overall = std::fs::read_to_string(dir.join("assets.id"))
        .unwrap_or_else(|_| panic!("no {}: run scripts/app/build_app_assets.py first", dir.join("assets.id").display()));

    let mut code = String::from("// Generated by build.rs from assets.json.\n");
    code.push_str("pub static UNITS: &[crate::assets::Unit] = &[\n");
    for u in units.as_array().unwrap_or_else(|| panic!("{} must be a list", manifest_path.display())) {
        let name = u["name"].as_str().expect("unit name");
        let id = u["id"].as_str().expect("unit id");
        let archive = dir.join(u["archive"].as_str().expect("unit archive"));
        assert!(archive.is_file(), "no {}: run scripts/app/build_app_assets.py first", archive.display());
        let remove = u["remove"]
            .as_array()
            .expect("unit remove")
            .iter()
            .map(|r| format!("{:?}", r.as_str().expect("remove path")))
            .collect::<Vec<_>>()
            .join(", ");
        code.push_str(&format!(
            "    crate::assets::Unit {{ name: {name:?}, id: {id:?}, remove: &[{remove}], archive: include_bytes!({:?}) }},\n",
            archive.canonicalize().unwrap().to_string_lossy()
        ));
        println!("cargo:rerun-if-changed={}", archive.display());
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("assets_table.rs");
    std::fs::write(&out, code).expect("write assets table");
    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rustc-env=DECKLIGHT_ASSETS_ID={}", overall.trim());
    tauri_build::build()
}
