"""Generate `constants.py` from the pinned core's `ocgapi_constants.h`.

Run after bumping the ygopro-core submodule:
    uv run python -m ygo_zero.engine._gen_constants
A unit test fails if the checked-in module is stale.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HEADER = ROOT / "third_party/ygopro-core/ocgapi_constants.h"
OUT = Path(__file__).with_name("constants.py")

# Extra constants the core defines outside the public header but which leak into the protocol.
_EXTRA = {"CARD_MARINE_DOLPHIN": 78734254, "CARD_TWINKLE_MOSS": 13857930}

_DEFINE = re.compile(r"^#define\s+([A-Z_][A-Z0-9_]*)\s+(.+?)\s*(?://.*|/\*.*)?$")


def parse(header_text: str) -> dict[str, int]:
    values: dict[str, int] = {}
    for line in header_text.splitlines():
        m = _DEFINE.match(line.strip())
        if not m:
            continue
        name, expr = m.groups()
        expr = re.sub(r"\((?:u?int\d+_t)\)", "", expr)
        expr = re.sub(r"\b(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", expr)
        expr = re.sub(r"\b0([0-7]+)\b", r"0o\1", expr)  # C octal literals (link markers)
        try:
            values[name] = int(eval(expr, {"__builtins__": {}}, dict(values)))
        except (SyntaxError, NameError, TypeError):  # include guards and non-numeric macros
            pass
    values.update(_EXTRA)
    return values


def render(values: dict[str, int]) -> str:
    lines = [
        '"""Constants from ygopro-core `ocgapi_constants.h`. GENERATED by `_gen_constants.py`; do not edit."""',
        "",
    ]
    lines += [f"{k} = 0x{v:X}" if v >= 0 else f"{k} = {v}" for k, v in values.items()]  # ruff-format style
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.write_text(render(parse(HEADER.read_text())))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
