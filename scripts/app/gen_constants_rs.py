"""Generate `rust/decklight-core/src/constants.rs` from `src/decklight/engine/constants.py`.

    uv run python scripts/app/gen_constants_rs.py [--out PATH] [--check]

The Python module is the oracle; the Rust file keeps every UPPER_CASE integer with the same name and
value, typed `u32` when it fits and `u64` otherwise. `--check` exits 2 when the file on disk is stale.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PY_CONSTANTS = ROOT / "src" / "decklight" / "engine" / "constants.py"
RS_OUT = ROOT / "rust" / "decklight-core" / "src" / "constants.rs"

HEADER = "//! Constants from ygopro-core `ocgapi_constants.h`, ported from\n//! `src/decklight/engine/constants.py`. GENERATED by `scripts/app/gen_constants_rs.py`; do not edit.\n"


def constants(path: Path = PY_CONSTANTS) -> list[tuple[str, int]]:
    """(name, value) in source order for every top-level UPPER_CASE integer assignment."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    out: list[tuple[str, int]] = []
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name) or not target.id.isupper():
            continue
        value = node.value
        if isinstance(value, ast.UnaryOp) and isinstance(value.op, ast.USub):
            inner = value.operand
            if isinstance(inner, ast.Constant) and isinstance(inner.value, int):
                out.append((target.id, -inner.value))
                continue
        if isinstance(value, ast.Constant) and isinstance(value.value, int):
            out.append((target.id, value.value))
    return out


def render(items: list[tuple[str, int]]) -> str:
    lines = [HEADER]
    for name, value in items:
        if value < 0:
            lines.append(f"pub const {name}: i64 = {value};")
        elif value <= 0xFFFF_FFFF:
            lines.append(f"pub const {name}: u32 = 0x{value:X};")
        else:
            lines.append(f"pub const {name}: u64 = 0x{value:X};")
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=RS_OUT)
    ap.add_argument("--check", action="store_true", help="exit 2 when --out is stale")
    a = ap.parse_args(argv)
    text = render(constants())
    if a.check:
        cur = a.out.read_text(encoding="utf-8") if a.out.exists() else ""
        if cur != text:
            print("ALERT constants.rs is stale: run scripts/app/gen_constants_rs.py", file=sys.stderr)
            return 2
        print("OK: constants.rs is current", file=sys.stderr)
        return 0
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out} ({len(constants())} constants)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
